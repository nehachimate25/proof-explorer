"""
Statement Analyzer (Master Dispatcher)
------------------------------------------
This is the dynamic analysis layer described in the project brief: given
ANY user-typed statement, normalize it, run it through a sequence of
rule-based pattern matchers (induction -> irrationality -> conditional
templates -> generic logic fallback), and return a structured result with
an honest support_level. Nothing here is generated by a language model --
every branch is a deterministic Python rule with a hand-verifiable
mathematical template behind it.

support_level meanings (see README):
  VERIFIED     -- deterministic rule/proof template, every step checked.
  SUPPORTED    -- pattern recognized, structured explanation given, but
                  full formal step-by-step proof isn't auto-generated.
  NEEDS_REVIEW -- partially understood, engine can't safely complete it.
  INVALID      -- empty, malformed, or not a mathematical statement.
"""

from .normalizer import normalize
from . import conditional_analyzer, induction_analyzer, irrationality_analyzer, logic_analyzer

MATH_SIGNALS = [
    "even", "odd", "divisible", "divides", "integer", "prime", "sum",
    "induction", "irrational", "squared", "cubed", "factorial", "sqrt",
    "\u221a", "for all", "for every", "=", "\u2265", "\u2264", ">=", "<=",
    "if ", " then", "n\u00b2", "n\u00b3", "+",
]


def analyze_statement(raw_text: str):
    if not raw_text or not raw_text.strip():
        return {
            "statement": raw_text,
            "support_level": "INVALID",
            "message": "Please enter a mathematical statement.",
        }

    text_norm = normalize(raw_text)
    t = text_norm.lower()

    if not any(sig in t for sig in MATH_SIGNALS):
        return {
            "statement": raw_text,
            "support_level": "INVALID",
            "message": (
                "I could not identify a clear proposition, variable, or mathematical relationship. "
                "Try a statement such as 'If n is even, then n\u00b2 is even.'"
            ),
        }

    result = induction_analyzer.analyze(text_norm)
    if result:
        result["statement"] = raw_text
        return result

    result = irrationality_analyzer.analyze(text_norm)
    if result:
        result["statement"] = raw_text
        return result

    result = conditional_analyzer.try_match(text_norm)
    if result:
        result["statement"] = raw_text
        return result

    if "if " in t and " then" in t:
        result = logic_analyzer.analyze(text_norm)
        if result:
            result["statement"] = raw_text
            return result

    return {
        "statement": raw_text,
        "support_level": "NEEDS_REVIEW",
        "message": (
            "I can partially understand this statement, but the current deterministic proof engine "
            "does not have a safe rule for completing this proof."
        ),
    }
